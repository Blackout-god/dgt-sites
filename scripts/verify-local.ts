import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { unzipSync } from 'fflate';
import type { Snapshot } from '@dream/catalog';
const base=process.env.HUB_INTERNAL_URL||'http://127.0.0.1:8787';
const vars=await readFile('apps/hub/.dev.vars','utf8');
const admin=vars.match(/^ADMIN_TOKEN="(.+)"$/m)?.[1];
const partner=vars.match(/^PARTNER_API_KEY="(.+)"$/m)?.[1];
assert.ok(admin&&partner);
const headers={Authorization:`Bearer ${partner}`};
const snapshot:Snapshot=JSON.parse(await readFile('.data/catalog.json','utf8'));
assert.equal((await fetch(`${base}/health`)).status,200);
assert.equal((await fetch(`${base}/api/v1/products`)).status,401);
const page=await fetch(`${base}/api/v1/products?brand=INKATOYS&lang=uk`,{headers}).then(r=>r.json()) as any;
assert.equal(page.total,68);assert.equal(page.products.length,50);
const page2=await fetch(`${base}/api/v1/products?page=2`,{headers}).then(r=>r.json()) as any;
assert.equal(page2.products.length,18);
assert.equal((await fetch(`${base}/api/v1/products?lang=en`,{headers})).status,400);
const p=snapshot.products.find(p=>p.id==='95098')!;
const original=await fetch(`${base}/media/${p.images[0].key}`);
assert.equal(original.status,200);
assert.deepEqual(Buffer.from(await original.arrayBuffer()),await readFile(`.data/${p.images[0].key}`));
const zip=await fetch(`${base}/downloads/${p.id}/photos.zip`);
assert.equal(zip.status,200);
const files=unzipSync(new Uint8Array(await zip.arrayBuffer()));
assert.equal(Object.keys(files).length,p.images.length);
for(const image of p.images)assert.deepEqual(Buffer.from(files[image.filename]),await readFile(`.data/${image.key}`));
assert.equal((await fetch(`${base}/downloads/96761/photos.zip`)).status,404);
const reject=await fetch(`${base}/internal/import`,{method:'POST',headers:{Authorization:`Bearer ${admin}`,'Content-Type':'application/json'},body:JSON.stringify({...snapshot,products:snapshot.products.slice(0,40)})});
assert.equal(reject.status,400);
const after=await fetch(`${base}/api/v1/products`,{headers}).then(r=>r.json()) as any;
assert.equal(after.total,68);
const beforeTimestamp=page.products[0].updated_at;
const repeat=await fetch(`${base}/internal/import`,{method:'POST',headers:{Authorization:`Bearer ${admin}`,'Content-Type':'application/json'},body:JSON.stringify(snapshot)});
assert.equal(repeat.status,200);
const repeated=await fetch(`${base}/api/v1/products`,{headers}).then(r=>r.json()) as any;
assert.equal(repeated.products[0].updated_at,beforeTimestamp);
console.log('PASS: health, API auth, 68 D1 products, pagination, language validation, R2 bytes, ZIP contents, missing photo, rejected partial import, idempotent import.');
